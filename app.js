  let demoIndex = 0;
  const demoThread = document.getElementById('demoThread');
  const demoLangTag = document.getElementById('demoLangTag');
  const demoDots = document.querySelectorAll('#demoDots span');

  function renderDemo(i){
    const step = demoSteps[i];
    demoLangTag.textContent = step.tag;
    demoThread.innerHTML = `
      <div class="demo-bubble cust">${step.cust}</div>
      <div class="demo-bubble ai">${step.ai}</div>`;
    requestAnimationFrame(()=>{
      demoThread.querySelectorAll('.demo-bubble').forEach((b,idx)=>{
        setTimeout(()=> b.classList.add('show'), idx*350);
      });
    });
    demoDots.forEach((d,idx)=> d.classList.toggle('active', idx===i));
  }
  renderDemo(0);
  setInterval(()=>{
    demoIndex = (demoIndex+1) % demoSteps.length;
    renderDemo(demoIndex);
  }, 4200);

  // ---------- FAQ accordion ----------
  document.querySelectorAll('.faq-item').forEach(item=>{
    const q = item.querySelector('.faq-q');
    const a = item.querySelector('.faq-a');
    q.addEventListener('click', ()=>{
      const isOpen = item.classList.contains('open');
      document.querySelectorAll('.faq-item').forEach(i=>{
        i.classList.remove('open');
        i.querySelector('.faq-a').style.maxHeight = null;
      });
      if(!isOpen){
        item.classList.add('open');
        a.style.maxHeight = a.scrollHeight + 'px';
      }
    });
  });

  // ---------- Scroll reveal ----------
